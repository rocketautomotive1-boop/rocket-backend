/** Mapeia seller_reputation.level_id do ML → bucket de tabela. */
export function reputationBucket(levelId?: string | null): ShippingReputation {
  const id = String(levelId || '').toLowerCase();
  if (id.includes('green')) return 'green';
  if (id.includes('yellow')) return 'yellow';
  if (id.includes('orange') || id.includes('red')) return 'red';
  // sem reputação / desconhecido → tratado como verde (até 50%, conforme ML)
  return 'green';
}

const idx = (uppers: number[], value: number) => {
  for (let i = 0; i < uppers.length; i++) if (value <= uppers[i]) return i;
  return uppers.length - 1;
};

/** Modalidade logística do ML que mapeamos para tabela. */
export type ShippingMode = 'traditional' | 'full';

/**
 * Frete oficial do ML por peso (kg) × preço (R$), conforme modalidade.
 * - 'traditional' (Coleta/Agências/drop_off): varia por reputação.
 * - 'full' (fulfillment): tabela única + regra "<R$29 paga no máx. 25% do preço".
 * Função PURA — base do adapter, testável sem rede. Retorna null se faltar peso.
 */
export function lookupShipping(params: {
  mode: ShippingMode;
  reputation: ShippingReputation;
  weightKg: number;
  price: number;
}): number | null {
  if (!params.weightKg || params.weightKg <= 0) return null;

  if (params.mode === 'full') {
    const row = idx(FULL_WEIGHT_UPPER_KG, params.weightKg);
    const col = idx(FULL_PRICE_UPPER_BRL, params.price);
    let cost = FULL[row]?.[col] ?? null;
    if (cost == null) return null;
    // Regra ML: produtos abaixo de R$29 pagam no máximo 25% do preço do produto.
    if (params.price > 0 && params.price < 29) cost = Math.min(cost, params.price * 0.25);
    return Math.round(cost * 100) / 100;
  }

  const matrix = MATRICES[params.reputation];
  const row = idx(WEIGHT_UPPER_KG, params.weightKg);
  const col = idx(PRICE_UPPER_BRL, params.price);
  return matrix[row]?.[col] ?? null;
}

/** Mapeia o logistic_type do ML → modalidade de tabela. */
export function shippingModeFor(logisticType: string): ShippingMode {
  return logisticType === 'fulfillment' ? 'full' : 'traditional';
}
